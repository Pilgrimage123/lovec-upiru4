/**
 * Resolve dialogue lookup helper
 */
function pick(arr) {
  if (!arr || arr.length === 0) return '';
  return arr[Math.floor(Math.random() * arr.length)];
}

export function getHunterDialogue(hunterId, category) {
  const hId = hunterId === 'classic' || hunterId === 'venca' ? 'classic' : hunterId;
  const h = HUNTER_DIALOGUES[hId] || HUNTER_DIALOGUES.ponocny;
  const list = h[category] || h.quips;
  return {
    speaker: h.name,
    icon: h.icon,
    text: pick(list)
  };
}

export function getEnemyDialogue(enemyIdOrArchetype, category) {
  let key = 'generic_enemy';
  const raw = String(enemyIdOrArchetype || '').toLowerCase();
  if (raw.includes('ponocny')) key = 'halapartnik';
  else if (raw.includes('dracula') || raw.includes('drakula')) key = 'boss_dracula';
  else if (raw.includes('dagmar')) key = 'boss_dagmar';
  else if (raw.includes('sosak')) key = 'boss_sosak';
  else if (raw.includes('praktikant')) key = 'praktikant';
  else if (raw.includes('urednik')) key = 'urednik';
  else if (raw.includes('drab')) key = 'drab';
  else if (raw.includes('vratny')) key = 'vratny_stit';
  else if (raw.includes('halapartnik')) key = 'halapartnik';
  else if (raw.includes('netopyr')) key = 'netopyr';

  const e = ENEMY_DIALOGUES[key] || ENEMY_DIALOGUES.generic_enemy;
  const list = e[category] || e.threats || e.quips;
  return {
    speaker: e.name,
    icon: e.icon,
    text: pick(list)
  };
}
